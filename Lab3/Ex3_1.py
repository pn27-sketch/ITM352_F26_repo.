def squareroot(n):
    return n**0.5

#Test the function
print(squareroot(4))  # Output: 2.0
print(squareroot(9))  # Output: 3.0
print(squareroot(16))  # Output: 4.0
print(squareroot(2))  # Output: 1.4142135623730951